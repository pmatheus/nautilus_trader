//! Bitget API credential storage and request signing helpers.

#![allow(unused_assignments)] // Fields are accessed externally, false positive from nightly

use std::fmt::{Debug, Formatter};

use aws_lc_rs::hmac;
use base64::prelude::*;
use ustr::Ustr;
use zeroize::ZeroizeOnDrop;

/// Bitget API credentials for signing requests.
///
/// Uses HMAC SHA256 for request signing as per Bitget API specifications.
/// Secrets are automatically zeroized on drop for security.
#[derive(Clone, ZeroizeOnDrop)]
pub struct Credential {
    #[zeroize(skip)]
    pub api_key: Ustr,
    pub api_passphrase: String,
    api_secret: Box<[u8]>,
}

impl Debug for Credential {
    fn fmt(&self, f: &mut Formatter<'_>) -> std::fmt::Result {
        f.debug_struct(stringify!(Credential))
            .field("api_key", &self.api_key)
            .field("api_passphrase", &self.api_passphrase)
            .field("api_secret", &"<redacted>")
            .finish()
    }
}

impl Credential {
    /// Creates a new [`Credential`] instance.
    #[must_use]
    pub fn new(api_key: String, api_secret: String, api_passphrase: String) -> Self {
        Self {
            api_key: api_key.into(),
            api_passphrase,
            api_secret: api_secret.into_bytes().into_boxed_slice(),
        }
    }

    /// Signs a request message according to the Bitget authentication scheme.
    ///
    /// The signature is generated by concatenating timestamp, method, requestPath, and body (if present),
    /// then using HMAC SHA256 to encrypt the string with the secret key, followed by Base64 encoding.
    ///
    /// # Arguments
    ///
    /// * `timestamp` - Unix timestamp in milliseconds as a string
    /// * `method` - HTTP method (GET, POST, etc.)
    /// * `request_path` - The request path including query parameters
    /// * `body` - Optional request body as bytes
    ///
    /// # Returns
    ///
    /// Base64-encoded HMAC SHA256 signature
    pub fn sign(
        &self,
        timestamp: &str,
        method: &str,
        request_path: &str,
        body: Option<&[u8]>,
    ) -> String {
        let mut message = Vec::with_capacity(
            timestamp.len() + method.len() + request_path.len() + body.map_or(0, |b| b.len()),
        );
        message.extend_from_slice(timestamp.as_bytes());
        message.extend_from_slice(method.as_bytes());
        message.extend_from_slice(request_path.as_bytes());
        if let Some(b) = body {
            message.extend_from_slice(b);
        }

        let key = hmac::Key::new(hmac::HMAC_SHA256, &self.api_secret[..]);
        let tag = hmac::sign(&key, &message);
        BASE64_STANDARD.encode(tag.as_ref())
    }
}

